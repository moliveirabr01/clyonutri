#!/bin/bash
set -u
umask 077

HTTPS="https://clyonutri.com"
HTTP="http://clyonutri.com"
OK=0
FAIL=0
TMP="$(mktemp -d)" || exit 1
trap 'rm -rf "$TMP"' EXIT
trap 'exit 130' INT TERM

for cmd in curl python3; do
  command -v "$cmd" >/dev/null || {
    echo "Dependência ausente: $cmd"
    exit 2
  }
done

pass() { OK=$((OK+1)); printf '  ✅ %s\n' "$1"; }
fail() { FAIL=$((FAIL+1)); printf '  ❌ %s\n' "$1"; }

header() {
  python3 - "$TMP/headers" "$1" <<'PY'
import sys
lines = open(sys.argv[1], errors="replace").read().splitlines()
key = sys.argv[2].lower() + ":"
for line in lines:
    if line.lower().startswith(key):
        print(line.split(":", 1)[1].strip())
PY
}

request() {
  local method="$1" url="$2"
  shift 2
  : > "$TMP/headers"
  : > "$TMP/body"
  printf '\n%s %s\n' "$method" "$url"

  if [ "$method" = HEAD ]; then
    STATUS="$(curl -sS --head \
      --connect-timeout 10 --max-time 20 \
      --proto '=http,https' \
      -D "$TMP/headers" -o /dev/null \
      -w '%{http_code}' "$@" "$url")"
  else
    STATUS="$(curl -sS \
      --connect-timeout 10 --max-time 20 \
      --proto '=http,https' \
      -X "$method" -D "$TMP/headers" -o "$TMP/body" \
      -w '%{http_code}' "$@" "$url")"
  fi

  local rc=$?
  if [ "$rc" -ne 0 ]; then
    fail "Falha de conexão/TLS: curl=$rc"
    return 1
  fi

  echo "  HTTP $STATUS"

  # Interrompe ao identificar bloqueio explícito do WAF.
  if grep -Eiq 'generated by Mod_Security|ModSecurity|automated traffic|verify you are human' "$TMP/body"; then
    fail "Bloqueio de segurança identificado; testes interrompidos."
    exit 2
  fi

  # Ritmo baixo: uma requisição por segundo.
  sleep 1
}

expect_status() {
  [ "$STATUS" = "$1" ] &&
    pass "Status esperado: $1" ||
    fail "Esperado $1; recebido $STATUS"
}

security_headers() {
  local hsts csp xfo nos count
  hsts="$(header Strict-Transport-Security)"
  csp="$(header Content-Security-Policy)"
  xfo="$(header X-Frame-Options)"
  nos="$(header X-Content-Type-Options)"

  count="$(header Strict-Transport-Security | wc -l | tr -d ' ')"
  if [ "$count" = 1 ] &&
     printf '%s' "$hsts" | grep -Eq '^max-age=[1-9][0-9]*([; ]|$)'; then
    pass "HSTS único: $hsts"
  else
    fail "HSTS ausente, duplicado ou sem max-age positivo"
  fi

  count="$(header Content-Security-Policy | wc -l | tr -d ' ')"
  if [ "$count" = 1 ] &&
     printf '%s' "$csp" | grep -Eq "frame-ancestors[[:space:]]+'none'([; ]|$)"; then
    pass "CSP efetiva única com bloqueio de enquadramento"
  else
    fail "CSP ausente, duplicada ou sem frame-ancestors 'none'"
  fi

  [ "$xfo" = DENY ] &&
    pass "X-Frame-Options: DENY" ||
    fail "X-Frame-Options ausente, duplicado ou diferente de DENY"

  [ "$nos" = nosniff ] &&
    pass "X-Content-Type-Options: nosniff" ||
    fail "nosniff ausente, duplicado ou incorreto"
}

echo "ClyoNutri — reteste externo"
date '+%Y-%m-%d %H:%M:%S %Z'
echo "Sem login, sem carga e sem seguir redirecionamentos."

# 1. Transporte HTTP: GET/HEAD.
for path in / /login '/login?teste=https'; do
  for method in GET HEAD; do
    request "$method" "$HTTP$path" || continue
    case "$STATUS" in
      301|308) pass "Redirecionamento permanente" ;;
      *) fail "HTTP deveria redirecionar; recebido $STATUS" ;;
    esac
    [ "$(header Location)" = "$HTTPS$path" ] &&
      pass "Destino HTTPS correto, preservando caminho/query" ||
      fail "Location ausente ou diferente do esperado"

    if [ "$method" = GET ]; then
      if grep -Eiq '<form([[:space:]>])' "$TMP/body"; then
        fail "Formulário servido por HTTP"
      else
        pass "Sem formulário na resposta HTTP"
      fi
    fi
  done
done

# 2. POST HTTP: valores exclusivamente fictícios.
request POST "$HTTP/login" \
  --data-urlencode 'email=pentest@example.invalid' \
  --data-urlencode 'password=Ficticio-Sem-Conta-2026' \
  --data-urlencode '_csrf_token=ficticio' && {
    expect_status 403
    [ -z "$(header Location)" ] &&
      pass "POST recusado sem redirecionar o corpo" ||
      fail "POST HTTP retornou Location"
  }

# 3. Cabeçalho forwarded não deve evitar HTTPS.
request GET "$HTTP/login" \
  -H 'X-Forwarded-Proto: https' && {
    case "$STATUS" in
      301|308) pass "Forwarded não contornou o redirecionamento" ;;
      *) fail "Verificar tratamento de X-Forwarded-Proto: HTTP $STATUS" ;;
    esac
  }

# 4. Páginas HTTPS e políticas efetivas.
for path in / /login; do
  for method in GET HEAD; do
    request "$method" "$HTTPS$path" || continue
    expect_status 200
    security_headers
  done
done

# 5. Proteção de páginas privadas sem sessão.
for path in /dashboard /admin; do
  request GET "$HTTPS$path" || continue
  expect_status 302
  [ "$(header Location)" = /login ] &&
    pass "Visitante enviado ao login" ||
    fail "Destino inesperado para visitante"
  [ ! -s "$TMP/body" ] &&
    pass "Corpo vazio" ||
    fail "Resposta contém corpo; revisar sem compartilhar dados pessoais"
  security_headers
done

# 6. API: sem token e com token fictício inválido.
for mode in ausente invalido; do
  args=(-H 'Origin: https://example.org')
  if [ "$mode" = invalido ]; then
    args+=(-H 'Authorization: Bearer pentest-token-invalido')
  fi

  request GET "$HTTPS/api/v1/patient/home" "${args[@]}" || continue
  expect_status 401

  case "$(header Content-Type)" in
    application/json*) pass "MIME JSON" ;;
    *) fail "Content-Type da API não é JSON" ;;
  esac

  if python3 - "$TMP/body" <<'PY'
import json, sys
try:
    obj = json.load(open(sys.argv[1]))
    assert isinstance(obj, dict)
    assert isinstance(obj.get("error"), str) and obj["error"]
    assert not any(k in obj for k in ("patient", "patients", "token", "data"))
except Exception:
    sys.exit(1)
PY
  then
    pass "JSON de erro no formato esperado"
  else
    fail "Corpo inesperado; revisar localmente sem divulgar dados"
  fi

  [ -z "$(header Access-Control-Allow-Origin)" ] &&
    pass "Origem externa sem autorização CORS nesta resposta" ||
    fail "Allow-Origin presente; investigar política CORS"

  security_headers
done

# 7. CSRF: uma tentativa com dados fictícios, sem token.
request POST "$HTTPS/login" \
  --data-urlencode 'email=pentest-csrf@example.invalid' \
  --data-urlencode 'password=Ficticio-Sem-Conta-2026' && {
    expect_status 403
    if python3 - "$TMP/body" <<'PY'
import json, sys
try:
    obj = json.load(open(sys.argv[1]))
    assert "csrf" in str(obj.get("error", "")).lower()
except Exception:
    sys.exit(1)
PY
    then
      pass "Rejeição explícita por CSRF"
    else
      fail "Confirmar motivo da rejeição CSRF"
    fi
  }

# 8. Arquivos sensíveis: conteúdo não é exibido.
for path in /.env /.git/HEAD; do
  request GET "$HTTPS$path" || continue
  case "$STATUS" in
    403|404) pass "Caminho sensível indisponível" ;;
    *) fail "Resposta inesperada no caminho sensível: $STATUS" ;;
  esac
done

printf '\nTOTAL: %s OK | %s FALHAS\n' "$OK" "$FAIL"
echo "Não cobre isolamento entre clínicas, sessões autenticadas ou jornadas sob CSP."
echo "Cabeçalhos corretos não comprovam ausência de XSS ou de outras vulnerabilidades."

[ "$FAIL" -eq 0 ]
