$calendar=new \ClyoNutri\Domain\Booking\BookingCalendarService($pdo);
$grouped=$calendar->agendaRules($c,$date,$date);
T::ok($calendar->windows($c,$prof,$date,[],true)===$calendar->windows($c,$prof,$date,[],true,$grouped[$date]),'Janelas com leitura em lote são idênticas à leitura canônica');
