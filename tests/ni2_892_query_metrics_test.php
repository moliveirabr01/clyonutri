T::ok($search->find($prof,60,$date)===null,'Busca sem jornada e sem abertura excepcional retorna null');
// With explicit opening on an otherwise closed calendar, the batch prefilter must not suppress it.
$pdo->prepare("INSERT INTO booking_calendar_exceptions (clinic_id,professional_id,rule_date,kind,label,start_time,end_time,created_at) VALUES (?,?,?,'open','Abertura TESTE','09:00','12:00',CURRENT_TIMESTAMP)")->execute([$c,$prof,$date]);
