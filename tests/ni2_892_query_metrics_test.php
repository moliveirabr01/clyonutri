putenv('V54_DB='.sys_get_temp_dir().'/ni2-892-tests-'.getmypid().'.sqlite');
require __DIR__.'/_v54_bootstrap.php';
use ClyoNutri\Core\Database\{ProfiledPdo,SchemaInfo};
use ClyoNutri\Domain\Appointment\{AppointmentService,NextAvailableSlot};

putenv('DB_QUERY_PROFILE=1');
$db=new ProfiledPdo('sqlite::memory:');
$db->setAttribute(PDO::ATTR_ERRMODE,PDO::ERRMODE_EXCEPTION);
$db->exec('CREATE TABLE sample (id INTEGER, value TEXT)');
$st=$db->prepare('INSERT INTO sample VALUES (?, ?)');
T::ok($db->metrics()->snapshot()['queries']===1,'Prepare não conta como execução');
$st->execute([1,'Dado confidencial TESTE']);$st->execute([2,'Outro TESTE']);
T::ok($db->metrics()->snapshot()['queries']===3,'Cada execute de statement reutilizado é contado');
T::ok($db->query('SELECT id FROM sample ORDER BY id',PDO::FETCH_COLUMN,0)->fetchAll()===[1,2],'query mantém modo de fetch e retorno');
T::ok($db->metrics()->snapshot()['queries']===4,'query contado uma única vez');
T::throws(fn()=>$db->exec('INVALID SQL'),'Erro SQL preservado');
T::ok($db->metrics()->snapshot()['queries']===5,'Consulta com erro também é contada');
T::ok(!str_contains(json_encode($db->metrics()->snapshot()),'confidencial') && !str_contains(json_encode($db->metrics()->snapshot()),'SELECT'),'Métricas sem SQL e parâmetros');
$db->metrics()->reset();SchemaInfo::reset();
T::ok(SchemaInfo::hasColumn($db,'sample','id') && SchemaInfo::hasColumn($db,'sample','value') && !SchemaInfo::hasColumn($db,'sample','missing'),'Metadata informa colunas presentes e ausentes');
T::ok($db->metrics()->snapshot()['queries']===1,'Metadados das colunas carregados uma vez por tabela');
T::ok(SchemaInfo::hasTable($db,'sample') && !SchemaInfo::hasTable($db,'missing'),'Catálogo de tabelas preserva presença/ausência');
T::ok($db->metrics()->snapshot()['queries']===2,'Catálogo de tabelas carregado uma vez');
$other=new ProfiledPdo('sqlite::memory:');
T::ok(!SchemaInfo::hasColumn($other,'sample','id') && !SchemaInfo::hasTable($other,'sample'),'Cache isolado por conexão');
$db->exec('ALTER TABLE sample ADD COLUMN extra TEXT');SchemaInfo::reset();
T::ok(SchemaInfo::hasColumn($db,'sample','extra'),'Reset após DDL atualiza schema');
putenv('APP_ENV=production');$prod=new ProfiledPdo('sqlite::memory:');$prod->query('SELECT 1');
T::ok(!$prod->metrics()->snapshot()['enabled'] && $prod->metrics()->snapshot()['queries']===0,'Produção nunca habilita perfil mesmo com flag 1');
putenv('APP_ENV=testing');putenv('DB_QUERY_PROFILE=0');$off=new ProfiledPdo('sqlite::memory:');$off->query('SELECT 1');
T::ok(!$off->metrics()->snapshot()['enabled'],'Flag desligada não perfila');
putenv('DB_QUERY_PROFILE=1');
$c=Fx::clinic($pdo,'Clínica TESTE 892');$u=Fx::user($pdo,$c,'Nutri TESTE 892','owner');Fx::act($u);
$prof=(int)$u['professional_id'];$date=date('Y-m-d',strtotime('+10 days'));
